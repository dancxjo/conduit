// Documentary verification of retained output; this does not run a provider.
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { captureDecimal } from '../../../proof/browser/exact-capture-json.mjs';
const digest = bytes => createHash('sha256').update(bytes).digest();
const hash = bytes => digest(bytes).toString('hex');
export function validateSpokenCapture(root, receipt, inventory) {
  const speech = receipt.journey.speech;
  assert.equal(speech.accepted, true, 'missing spoken encounter');
  assert.equal(speech.speaker_delivery, false);
  assert.equal(speech.human_listening, false);
  assert.equal(speech.before.face.identity, speech.after.face.identity);
  assert.equal(JSON.stringify(speech.before.face.properties), JSON.stringify(speech.after.face.properties));
  const { execution: reading, route } = speech.evidence;
  const template = reading.template;
  const view = receipt.journey.after_terminal.view;
  assert.equal(template.template_identity, 'spoken/control@1');
  assert.equal(template.source_face_identity, view.face_id);
  assert.equal(template.source_face_identity, speech.before.face.identity);
  assert.equal(captureDecimal(template.source_face_revision), captureDecimal(view.face_revision));
  assert.equal(route.body_id, receipt.body_id);
  assert.equal(route.face_id, view.face_id);
  assert.equal(captureDecimal(route.face_revision), captureDecimal(view.face_revision));
  assert.equal(route.profile, 'hosted-presentation');
  assert.ok(!route.interaction_line, 'spoken route must be read only');
  assert.equal(route.owner_host.host_id, receipt.owner_host_id);
  assert.equal(route.mask_host.host_id, receipt.presentation_peer_host_id);
  const words = Buffer.from(template.wording);
  assert.ok(words.length > 0 && words.length <= 8192);
  assert.equal(reading.completed_wording_bytes, words.length);
  assert.deepEqual(reading.completed_wording_sha256, [...digest(words)]);
  assert.deepEqual(template.wording_digest, [...digest(words)]);
  assert.ok(reading.frames.length > 0 && reading.frames.length <= 64);
  assert.equal(speech.artifacts.frames.length, reading.frames.length);
  const plays = new Set();
  const pcm = [];
  let offset = 0;
  let header;
  for (const [index, frame] of reading.frames.entries()) {
    assert.equal(frame.frame_index, index);
    assert.equal(frame.source_face_id, template.source_face_identity);
    assert.equal(frame.source_show_id, reading.source_show.show_id);
    assert.equal(frame.host_id, receipt.presentation_peer_host_id);
    assert.equal(frame.host_id, reading.source_show.show.host_id);
    assert.equal(frame.boot_id, reading.source_show.show.boot_id);
    assert.ok(!plays.has(frame.speech_play_id)); plays.add(frame.speech_play_id);
    assert.match(frame.provider_sha256, /^[a-f0-9]{64}$/);
    assert.equal(frame.provider_sha256, reading.frames[0].provider_sha256);
    assert.ok(frame.text_bytes > 0 && frame.text_bytes <= 96);
    const text = words.subarray(offset, offset + frame.text_bytes);
    new TextDecoder('utf-8', { fatal: true }).decode(text);
    assert.deepEqual(frame.text_sha256, [...digest(text)]);
    offset += frame.text_bytes;
    const retained = speech.artifacts.frames[index];
    assert.equal(retained.frame_index, index);
    assert.equal(retained.path, `capture/spoken-${String(index).padStart(2, '0')}.wav`);
    assert.ok(inventory.has(retained.path));
    const wav = readFileSync(path.join(root, retained.path));
    assert.equal(wav.length, retained.bytes);
    assert.equal(hash(wav), retained.sha256);
    assert.ok(wav.length > 44 && wav.length <= 44 + 30 * 48000 * 4);
    assert.equal(wav.subarray(0, 4).toString(), 'RIFF');
    assert.equal(wav.readUInt32LE(4), wav.length - 8);
    assert.equal(wav.subarray(8, 16).toString(), 'WAVEfmt ');
    assert.equal(wav.readUInt32LE(16), 16);
    assert.equal(wav.readUInt16LE(20), 1);
    assert.equal(wav.readUInt16LE(22), 2);
    assert.equal(wav.readUInt32LE(24), 48000);
    assert.equal(wav.readUInt32LE(28), 192000);
    assert.equal(wav.readUInt16LE(32), 4);
    assert.equal(wav.readUInt16LE(34), 16);
    assert.equal(wav.subarray(36, 40).toString(), 'data');
    assert.equal(wav.readUInt32LE(40), wav.length - 44);
    assert.equal(frame.pcm_bytes, wav.length - 44);
    assert.ok(['pcm', 'wav'].includes(frame.artifact_digest_scope));
    assert.equal(hash(frame.artifact_digest_scope === 'pcm' ? wav.subarray(44) : wav), frame.artifact_sha256);
    header ??= Buffer.from(wav.subarray(0, 44));
    pcm.push(wav.subarray(44));
  }
  assert.equal(offset, words.length);
  const recording = speech.artifacts.recording;
  assert.equal(recording.path, 'capture/spoken-reading.wav');
  assert.ok(inventory.has(recording.path));
  assert.deepEqual(recording.source_frames, speech.artifacts.frames.map(frame => frame.path));
  const payload = Buffer.concat(pcm);
  header.writeUInt32LE(payload.length + 36, 4);
  header.writeUInt32LE(payload.length, 40);
  const joined = Buffer.concat([header, payload]);
  assert.equal(joined.length, recording.bytes);
  assert.equal(hash(joined), recording.sha256);
  assert.deepEqual(readFileSync(path.join(root, recording.path)), joined);
}
