fn render_u32_slice(output: &mut String, name: &str, values: impl Iterator<Item = u32>) {
    let values = values.collect::<Vec<_>>();
    writeln!(
        output,
        "pub const {name}: [u32; {}] = {:?};",
        values.len(),
        values
    )
    .expect("String writes cannot fail");
}
